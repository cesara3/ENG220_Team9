%% Cuba Health Presentation: Community Comparisons
clear;
clc;
close all;

%% 1. Read the three CSV files
conditions = readtable('cuba_health_conditions.csv', ...
    'TextType', 'string');

risks = readtable('cuba_health_risks.csv', ...
    'TextType', 'string');

access = readtable('cuba_healthcare_access.csv', ...
    'TextType', 'string');

health = [conditions; risks];

%% 2. Define community order and colors
locations = ["Cuba", "Bernalillo", "Rio Rancho"];

colors = [
    0.10 0.42 0.60
    0.85 0.42 0.08
    0.35 0.53 0.38
];

%% 3. Graph 1: Compare health conditions and risks
healthCodes = [
    "BPHIGH"
    "OBESITY"
    "LPA"
    "DIABETES"
    "DEPRESSION"
];

healthLabels = {
    'High blood pressure'
    'Obesity'
    'No leisure-time activity'
    'Diagnosed diabetes'
    'Diagnosed depression'
};

% Read age-adjusted estimates and confidence intervals.
[healthValues, healthLower, healthUpper] = ...
    getEstimates(health, locations, healthCodes);

fig1 = drawComparison( ...
    healthValues, healthLower, healthUpper, ...
    healthLabels, locations, colors, ...
    'Health Conditions and Risks Across Three Communities', ...
    'Adults age 18+ | 2023 data | Age-adjusted estimates', ...
    55);

exportgraphics(fig1, 'slide1_health_comparison.png', ...
    'Resolution', 300, 'BackgroundColor', 'white');

%% 4. Graph 2: Compare preventive-care visits
visitCodes = ["CHECKUP"; "DENTAL"];

visitLabels = {
    'Routine checkup (2023)'
    'Dental visit (2022)'
};

[visitValues, visitLower, visitUpper] = ...
    getEstimates(access, locations, visitCodes);

fig2 = drawComparison( ...
    visitValues, visitLower, visitUpper, ...
    visitLabels, locations, colors, ...
    'Preventive-Care Visits Across Three Communities', ...
    'Visit within the past year | Age-adjusted estimates', ...
    90);

exportgraphics(fig2, 'slide2_preventive_care.png', ...
    'Resolution', 300, 'BackgroundColor', 'white');

%% 5. Confirm the images were saved
disp('Created slide1_health_comparison.png');
