%% Local function: Read estimates in the requested order
function [values, lower, upper] = ...
    getEstimates(T, locations, codes)

    values = zeros(numel(codes), numel(locations));
    lower = zeros(size(values));
    upper = zeros(size(values));

    for town = 1:numel(locations)
        for measure = 1:numel(codes)

            row = T(T.location == locations(town) & ...
                    T.measure_id == codes(measure), :);

            assert(height(row) == 1, ...
                'Expected one row for %s, %s.', ...
                char(locations(town)), char(codes(measure)));

            values(measure,town) = row.age_adjusted_percent;
            lower(measure,town) = row.age_adjusted_ci95_low;
            upper(measure,town) = row.age_adjusted_ci95_high;
        end
    end
end

%% Local function: Create a readable grouped bar graph
function fig = drawComparison(values, lower, upper, ...
    labels, locations, colors, mainTitle, subTitle, yMaximum)

    fig = figure( ...
        'Color', 'white', ...
        'Position', [50 50 1500 850]);

    % Leave room for titles, legend, and source note.
    ax = axes(fig, 'Position', [0.09 0.25 0.87 0.58]);

    b = bar(ax, values, 'grouped');
    hold(ax, 'on');

    for town = 1:numel(locations)
        b(town).FaceColor = colors(town,:);
        b(town).EdgeColor = 'none';

        x = b(town).XEndPoints;
        y = values(:,town)';

        % Black lines show 95% confidence intervals.
        errorbar(ax, x, y, ...
            y-lower(:,town)', ...
            upper(:,town)'-y, ...
            'k.', ...
            'LineWidth', 1.5, ...
            'CapSize', 8, ...
            'HandleVisibility', 'off');

        % Explicitly make all percentage labels black.
        for measure = 1:size(values,1)
            text(ax, x(measure), upper(measure,town)+1.2, ...
                sprintf('%.1f%%', y(measure)), ...
                'HorizontalAlignment', 'center', ...
                'FontSize', 12, ...
                'FontWeight', 'bold', ...
                'Color', 'black');
        end
    end

    % Dark, readable axes and category labels.
    set(ax, ...
        'Color', 'white', ...
        'XColor', 'black', ...
        'YColor', 'black', ...
        'FontName', 'Arial', ...
        'FontSize', 14, ...
        'FontWeight', 'bold', ...
        'LineWidth', 1.2, ...
        'Box', 'off', ...
        'TickLabelInterpreter', 'none');

    xticks(ax, 1:numel(labels));
    xticklabels(ax, labels);
    xtickangle(ax, 0);

    ylim(ax, [0 yMaximum]);
    yticks(ax, 0:10:yMaximum);

    ylabel(ax, 'Age-adjusted estimated percentage (%)', ...
        'FontSize', 16, ...
        'FontWeight', 'bold', ...
        'Color', 'black');

    % Explicitly format both title lines.
    title(ax, {mainTitle; subTitle}, ...
        'FontSize', 20, ...
        'FontWeight', 'bold', ...
        'Color', 'black', ...
        'Interpreter', 'none');

    % Light grid lines keep attention on the bars.
    grid(ax, 'on');
    ax.XGrid = 'off';
    ax.YGrid = 'on';
    ax.GridColor = [0.65 0.65 0.65];
    ax.GridAlpha = 0.25;

    % Explicitly format the legend text and background.
    lgd = legend(ax, b, cellstr(locations), ...
        'Location', 'southoutside', ...
        'Orientation', 'horizontal');

    set(lgd, ...
        'TextColor', 'black', ...
        'Color', 'white', ...
        'FontSize', 15, ...
        'FontWeight', 'bold', ...
        'Box', 'off');

    % Source note included in the exported image.
    annotation(fig, 'textbox', [0.08 0.035 0.88 0.07], ...
        'String', ...
        ['Source: CDC PLACES, 2025 release. ' ...
         'Model-based estimates; black lines show 95% confidence intervals.'], ...
        'Color', 'black', ...
        'FontSize', 12, ...
        'FontWeight', 'bold', ...
        'HorizontalAlignment', 'center', ...
        'EdgeColor', 'none', ...
        'Interpreter', 'none');

    hold(ax, 'off');
end